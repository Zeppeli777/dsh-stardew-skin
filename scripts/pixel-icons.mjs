/** 16×16 ASCII 网格 → 单色 currentColor 像素画；横向游程合并成一条 path。 */
export function pixelSvg(rows) {
  let d = ''
  for (let y = 0; y < rows.length; y++) {
    const row = rows[y]
    for (let x = 0; x < row.length;) {
      if (row[x] !== '#') { x++; continue }
      const x0 = x
      while (x < row.length && row[x] === '#') x++
      d += `M${x0} ${y}h${x - x0}v1h${x0 - x}z`
    }
  }
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" shape-rendering="crispEdges"><path d="${d}" fill="currentColor"/></svg>`
}

