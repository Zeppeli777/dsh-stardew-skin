/**
 * 组装 ThemeDefinition.icons：官方精灵按 regular/medium 两个权重各存一份，
 * 像素画与权重无关，同图替换（共 glyph×2 个 symbol）。
 */
export function buildIcons() {
  const icons = {}
  for (const [glyph, rows] of Object.entries(PIXEL_ICONS)) {
    for (const weight of ['regular', 'medium']) {
      icons[`dsw-icon-${glyph}-${weight}`] = pixelSvg(rows)
    }
  }
  return icons
}
